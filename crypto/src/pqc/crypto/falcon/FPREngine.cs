        internal static FalconFpr FprOf(long i) => Fpr((double)i);

        internal static long FprRInt(FalconFpr x)
        {
            /*
             * We do not want to use llrint() since it might be not constant-time.
             *
             * Suppose that x >= 0. If x >= 2^52, then it is already an integer. Otherwise, if x < 2^52, then computing
             * x+2^52 will yield a value that will be rounded to the nearest integer with exactly the right rules
             * (round-to-nearest-even).
             *
             * In order to have constant-time processing, we must do the computation for both x >= 0 and x < 0 cases,
             * and use a cast to an integer to access the sign and select the proper value. Such casts also allow us to
             * find out if |x| < 2^52.
             */
            long sx = (long)(x.v - 1.0);
            long tx = (long)x.v;
            long rp = (long)(x.v + 4503599627370496.0) - 4503599627370496;
            long rn = (long)(x.v - 4503599627370496.0) + 4503599627370496;

            /*
             * If tx >= 2^52 or tx < -2^52, then result is tx. Otherwise, if sx >= 0, then result is rp. Otherwise,
             * result is rn. We use the fact that when x is close to 0 (|x| <= 0.25) then both rp and rn are correct;
             * and if x is not close to 0, then trunc(x-1.0) yields the appropriate sign.
             */

            /*
             * Clamp rp to zero if tx < 0.
             * Clamp rn to zero if tx >= 0.
             */
            long m = sx >> 63;
            rn &= m;
            rp &= ~m;

            /*
             * Get the 12 upper bits of tx; if they are not all zeros or all ones, then tx >= 2^52 or tx < -2^52, and we
             * clamp both rp and rn to zero. Otherwise, we clamp tx to zero.
             */
            uint ub = (uint)((ulong)tx >> 52);
            m = -(long)((((ub + 1) & 0xFFF) - 2) >> 31);
            rp &= m;
            rn &= m;
            tx &= ~m;

            // Only one of tx, rn or rp (at most) can be non-zero at this point.
            return tx | rn | rp;
        }

        internal static long FprFloor(FalconFpr x)
        {
            /*
             * The cast performs a trunc() (rounding toward 0) and thus is wrong by 1 for most negative values. The
             * correction below is constant-time as long as the compiler turns the floating-point conversion result into
             * a 0/1 integer without a conditional branch or another non-constant-time construction. This should hold on
             * all modern architectures with an FPU (and if it is false on a given arch, then chances are that the FPU
             * itself is not constant-time, making the point moot).
             */
            long r = (long)x.v;
            return r - ((x.v < (double)r) ? 1 : 0);
        }

        internal static long FprTrunc(FalconFpr x) => (long)x.v;

        internal static FalconFpr FprAdd(FalconFpr x, FalconFpr y) => Fpr(x.v + y.v);

        internal static FalconFpr FprSub(FalconFpr x, FalconFpr y) => Fpr(x.v - y.v);

        internal static FalconFpr FprNeg(FalconFpr x) => Fpr(-x.v);

        internal static FalconFpr FprHalf(FalconFpr x) => Fpr(x.v * 0.5);

        internal static FalconFpr FprDouble(FalconFpr x) => Fpr(x.v + x.v);

        internal static FalconFpr FprMul(FalconFpr x, FalconFpr y) => Fpr(x.v * y.v);

        internal static FalconFpr FprSqr(FalconFpr x) => Fpr(x.v * x.v);

        internal static FalconFpr FprInv(FalconFpr x) => Fpr(1.0 / x.v);

        internal static FalconFpr FprDiv(FalconFpr x, FalconFpr y) => Fpr(x.v / y.v);

        internal static FalconFpr FprSqrt(FalconFpr x) => Fpr(System.Math.Sqrt(x.v));

        internal static bool FprLessThan(FalconFpr x, FalconFpr y) => x.v < y.v;

        internal static ulong FprExpMP63(FalconFpr x, FalconFpr ccs)
        {
            /*
             * Polynomial approximation of exp(-x) is taken from FACCT:
             *   https://eprint.iacr.org/2018/1234
             * Specifically, values are extracted from the implementation referenced from the FACCT article, and
             * available at:
             *   https://github.com/raykzhao/gaussian
             * Tests over more than 24 billions of random inputs in the 0..log(2) range have never shown a deviation
             * larger than 2^(-50) from the true mathematical value.
             */

            // Normal implementation uses Horner's method, which minimizes the number of operations.

            double d = x.v, y;
            y = 0.000000002073772366009083061987;
            y = 0.000000025299506379442070029551 - y * d;
            y = 0.000000275607356160477811864927 - y * d;
            y = 0.000002755586350219122514855659 - y * d;
            y = 0.000024801566833585381209939524 - y * d;
            y = 0.000198412739277311890541063977 - y * d;
            y = 0.001388888894063186997887560103 - y * d;
            y = 0.008333333327800835146903501993 - y * d;
            y = 0.041666666666110491190622155955 - y * d;
            y = 0.166666666666984014666397229121 - y * d;
            y = 0.500000000000019206858326015208 - y * d;
            y = 0.999999999999994892974086724280 - y * d;
            y = 1.000000000000000000000000000000 - y * d;
            y *= ccs.v;
            return (ulong)(y * FprPosTwo63.v);
        }

